"""Conversation starter: periodically sends a question to a peer agent.

Every ``interval`` seconds the starter sends one direct message to its
peer. The message is generated by the local model from the agent's
interests, or taken from the personality's opening questions when the
model is unavailable. Nothing is sent while the pause switch is on.

Replies are governed by the dialogue guard on the receiving side, so the
peer answers at most 10 times per 5 minutes unless a human message
resets the limit.
"""

from __future__ import annotations

import asyncio
import logging
from collections.abc import Awaitable, Callable

from nexus_cove.agents.backends.ollama_replier import ModelUnavailable, OllamaReplier
from nexus_cove.agents.pause import is_paused
from nexus_cove.agents.personality import Personality

log = logging.getLogger("nexus_cove.starter")

DEFAULT_INTERVAL_SECONDS = 300.0


class ConversationStarter:
    def __init__(
        self,
        peer: str,
        personality: Personality,
        interval: float = DEFAULT_INTERVAL_SECONDS,
        replier: OllamaReplier | None = None,
        paused: Callable[[], bool] = is_paused,
    ) -> None:
        if interval <= 0:
            raise ValueError("interval must be positive")
        self.peer = peer
        self.personality = personality
        self.interval = interval
        self._replier = replier
        self._paused = paused
        self._turn = 0

    async def fire_once(self, send: Callable[[str], Awaitable[None]]) -> str | None:
        """Send one starter message. Returns the text sent, or None if paused."""
        if self._paused():
            log.info("Paused: no conversation starter sent", extra={"event": "starter_paused"})
            return None
        interest = self.personality.interests[self._turn % len(self.personality.interests)]
        text = await self._generate(interest)
        self._turn += 1
        await send(text)
        log.info("Sent conversation starter", extra={"event": "starter_sent", "peer": self.peer})
        return text

    async def run(self, send: Callable[[str], Awaitable[None]]) -> None:
        while True:
            await asyncio.sleep(self.interval)
            await self.fire_once(send)

    async def _generate(self, interest: str) -> str:
        if self._replier is not None:
            prompt = (
                f"Ask {self.peer} one short, curious question about {interest}. "
                "Write only the question."
            )
            try:
                return await self._replier.areply(prompt)
            except ModelUnavailable as exc:
                log.error(
                    "Model unavailable for starter; using an opening question",
                    extra={"event": "starter_fallback", "error": str(exc)},
                )
        options = self.personality.opening_questions
        return options[self._turn % len(options)]
